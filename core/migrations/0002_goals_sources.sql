-- Schema version 2: flexible goals, forgiving streaks (freeze days) and automatic data sources.
ALTER TABLE trackers ADD COLUMN goal_mode TEXT NOT NULL DEFAULT 'daily' CHECK (goal_mode IN ('daily','weekly'));
-- In weekly mode: number of qualifying days (value >= goal) needed per week.
ALTER TABLE trackers ADD COLUMN weekly_target INTEGER NOT NULL DEFAULT 7 CHECK (weekly_target BETWEEN 1 AND 7);
-- How many scheduled days per calendar month may be frozen without breaking a streak.
ALTER TABLE trackers ADD COLUMN freezes_per_month INTEGER NOT NULL DEFAULT 0 CHECK (freezes_per_month BETWEEN 0 AND 10);
-- 'manual' for typed entries, 'git:<source id>' for entries generated by a source sync.
ALTER TABLE entries ADD COLUMN source TEXT NOT NULL DEFAULT 'manual';
CREATE TABLE freezes (
  tracker_id TEXT NOT NULL REFERENCES trackers(id) ON DELETE CASCADE,
  date       TEXT NOT NULL CHECK (date GLOB '[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]'),
  PRIMARY KEY (tracker_id, date)
);
CREATE TABLE sources (
  id          TEXT PRIMARY KEY,
  tracker_id  TEXT NOT NULL REFERENCES trackers(id) ON DELETE CASCADE,
  kind        TEXT NOT NULL CHECK (kind IN ('git')),
  path        TEXT NOT NULL,
  last_synced TEXT,
  UNIQUE (tracker_id, path)
);
